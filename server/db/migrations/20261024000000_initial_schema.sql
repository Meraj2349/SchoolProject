CREATE INDEX "idx_attendance_sms_due" ON "AttendanceSms" ("status", "due_at");
CREATE INDEX "idx_attendance_sms_branch_day" ON "AttendanceSms" ("branch_id", "class_date");

-- ============================================================
-- MySQL's ON UPDATE CURRENT_TIMESTAMP: bump the named column when a row
-- really changes, unless the UPDATE set that column itself.
-- ============================================================
CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF to_jsonb(NEW) -> TG_ARGV[0] IS NOT DISTINCT FROM to_jsonb(OLD) -> TG_ARGV[0] THEN
        NEW := jsonb_populate_record(NEW, jsonb_build_object(TG_ARGV[0], now()));
    END IF;
    RETURN NEW;
END;
$$;

