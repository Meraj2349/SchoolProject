-- Full schema for PostgreSQL, translated from Sql/database.sql (MySQL) plus
-- star_family_branches_migration.sql. Names keep MySQL's spelling and are
-- quoted, so the API returns the same keys as before.
--
-- Translation rules:
--   INT AUTO_INCREMENT      → integer identity (bigint for the quiz tables)
--   ENUM(...)               → varchar + CHECK
--   TINYINT UNSIGNED        → smallint + CHECK (>= 0)
--   TIMESTAMP / DATETIME    → timestamptz
--   JSON                    → jsonb
--   ON UPDATE CURRENT_TIMESTAMP → set_updated_at() trigger (bottom of file)
--   MySQL's utf8mb4_0900_ai_ci (case and accent insensitive) → the ci
--   collation below on every text column: =, LIKE, UNIQUE and ORDER BY
--   behave as before. LIKE on it needs PostgreSQL 18.

-- Text compares like MySQL's default collation: ignoring case and accents.
