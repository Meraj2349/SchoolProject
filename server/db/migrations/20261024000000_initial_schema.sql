    "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "branch_id" integer NOT NULL REFERENCES "Branches" ("id"),
    "student_id" integer NOT NULL,
    "year" smallint NOT NULL,
    "month" smallint NOT NULL,
    "class_name" varchar(20) COLLATE ci NOT NULL, -- class and section when billed, so reports survive promotions
    "section" varchar(10) COLLATE ci,
    "due_date" date NOT NULL,
    "status" varchar(7) COLLATE ci NOT NULL DEFAULT 'unpaid' CHECK ("status" IN ('unpaid', 'partial', 'paid')),
    "created_by" integer NULL,
    "created_at" timestamptz DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "uq_invoice_student_month" UNIQUE ("student_id", "year", "month"),
    CONSTRAINT "fk_invoices_student" FOREIGN KEY ("student_id") REFERENCES "Students" ("StudentID") ON DELETE RESTRICT
);
CREATE INDEX "idx_invoices_branch_period" ON "FeeInvoices" ("branch_id", "year", "month");

-- Invoice lines are copied at billing time; discounts are stored negative.
CREATE TABLE "FeeInvoiceItems" (
    "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "invoice_id" integer NOT NULL REFERENCES "FeeInvoices" ("id") ON DELETE CASCADE,
    "kind" varchar(9) COLLATE ci NOT NULL CHECK ("kind" IN ('tuition', 'extra', 'discount', 'late_fine')),
    "label" varchar(150) COLLATE ci NOT NULL,
    "amount" numeric(10, 2) NOT NULL
);

-- Payments are never deleted, only voided, so the history stays auditable.
CREATE TABLE "FeePayments" (
    "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "branch_id" integer NOT NULL REFERENCES "Branches" ("id"),
    "invoice_id" integer NOT NULL REFERENCES "FeeInvoices" ("id"),
    "amount" numeric(10, 2) NOT NULL,
    "method" varchar(5) COLLATE ci NOT NULL CHECK ("method" IN ('cash', 'bkash', 'nagad', 'bank', 'other')),
    "paid_on" date NOT NULL,
    "receipt_no" varchar(30) COLLATE ci NOT NULL,
    "received_by" integer NULL,
    "note" varchar(255) COLLATE ci,
    "voided_at" timestamptz NULL,
    "voided_by" integer NULL,
    "void_reason" varchar(255) COLLATE ci,
    "created_at" timestamptz DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "uq_payment_receipt" UNIQUE ("branch_id", "receipt_no")
);
CREATE INDEX "idx_payments_invoice" ON "FeePayments" ("invoice_id");

-- Last receipt number issued per branch and year (locked while issuing one).
CREATE TABLE "FeeReceiptCounters" (
    "branch_id" integer NOT NULL REFERENCES "Branches" ("id"),
    "year" smallint NOT NULL,
    "last_seq" integer NOT NULL DEFAULT 0,
    PRIMARY KEY ("branch_id", "year")
);

